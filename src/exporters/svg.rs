use crate::ir::{DecoupledDocument, Geometry};
use std::fs::File;
use std::io::{BufWriter, Write};
use std::path::Path;

/// Exports recovered vector layers, CubicBezier curves, and RegularGrid lattices into a standalone,
/// human-auditable SVG with original coordinate `viewBox` and embedded provenance attributes (`data-offset`, `data-confidence`).
pub fn export_svg(doc: &DecoupledDocument, path: &Path) -> std::io::Result<()> {
    let file = File::create(path)?;
    let mut out = BufWriter::new(file);

    let bbox = doc.global_bbox.unwrap_or(crate::ir::BoundingBox {
        min_x: 0.0,
        min_y: 0.0,
        max_x: 1000.0,
        max_y: 1000.0,
        min_z: None,
        max_z: None,
    });

    let width_span = (bbox.max_x - bbox.min_x).abs().max(1.0);
    let height_span = (bbox.max_y - bbox.min_y).abs().max(1.0);
    let pad_x = width_span * 0.05;
    let pad_y = height_span * 0.05;
    let vb_x = bbox.min_x - pad_x;
    let vb_y = bbox.min_y - pad_y;
    let vb_w = width_span + 2.0 * pad_x;
    let vb_h = height_span + 2.0 * pad_y;
    let stroke_w = (vb_w.max(vb_h) * 0.0035).max(0.0001);
    let pt_r = stroke_w * 2.2;

    writeln!(out, "<?xml version=\"1.0\" encoding=\"UTF-8\"?>")?;
    writeln!(
        out,
        "<!-- Generated by OpenArchive Decoupler v{} | Source: {} (SHA-256: {}) -->",
        doc.metadata.tool_version, doc.metadata.source_filename, doc.metadata.sha256
    )?;
    writeln!(
        out,
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"{} {} {} {}\" width=\"1200\" height=\"900\">",
        vb_x, vb_y, vb_w, vb_h
    )?;
    writeln!(
        out,
        "  <rect x=\"{}\" y=\"{}\" width=\"{}\" height=\"{}\" fill=\"#0f172a\" />",
        vb_x, vb_y, vb_w, vb_h
    )?;

    for layer in &doc.layers {
        writeln!(
            out,
            "  <g id=\"{}\" data-layer-name=\"{}\" stroke=\"{}\" fill=\"{}\" stroke-width=\"{}\">",
            layer.id, layer.name, layer.style_stroke, layer.style_fill, stroke_w
        )?;

        for feat in &layer.features {
            let off = feat.provenance.span.offset;
            let len = feat.provenance.span.length;
            let conf = feat.provenance.confidence.composite;
            let lineage = &feat.provenance.stream_lineage;

            match &feat.geometry {
                Geometry::Point { coord, .. } => {
                    writeln!(
                        out,
                        "    <circle id=\"{}\" cx=\"{}\" cy=\"{}\" r=\"{}\" fill=\"{}\" data-offset=\"{}\" data-length=\"{}\" data-stream-lineage=\"{}\" data-confidence=\"{:.4}\" />",
                        feat.id, coord[0], coord[1], pt_r, layer.style_stroke, off, len, lineage, conf
                    )?;
                }
                Geometry::MultiPoint { coords } => {
                    writeln!(
                        out,
                        "    <g id=\"{}\" data-offset=\"{}\" data-length=\"{}\" data-stream-lineage=\"{}\" data-confidence=\"{:.4}\">",
                        feat.id, off, len, lineage, conf
                    )?;
                    for c in coords {
                        writeln!(
                            out,
                            "      <circle cx=\"{}\" cy=\"{}\" r=\"{}\" fill=\"{}\" />",
                            c[0], c[1], pt_r, layer.style_stroke
                        )?;
                    }
                    writeln!(out, "    </g>")?;
                }
                Geometry::LineString { coords } => {
                    let pts_str = coords
                        .iter()
                        .map(|c| format!("{},{}", c[0], c[1]))
                        .collect::<Vec<_>>()
                        .join(" ");
                    writeln!(
                        out,
                        "    <polyline id=\"{}\" fill=\"none\" points=\"{}\" data-offset=\"{}\" data-length=\"{}\" data-stream-lineage=\"{}\" data-confidence=\"{:.4}\" />",
                        feat.id, pts_str, off, len, lineage, conf
                    )?;
                }
                Geometry::MultiLineString { lines } => {
                    let mut d = String::new();
                    for line in lines {
                        for (i, c) in line.iter().enumerate() {
                            if i == 0 {
                                d.push_str(&format!("M {} {} ", c[0], c[1]));
                            } else {
                                d.push_str(&format!("L {} {} ", c[0], c[1]));
                            }
                        }
                    }
                    writeln!(
                        out,
                        "    <path id=\"{}\" fill=\"none\" d=\"{}\" data-offset=\"{}\" data-length=\"{}\" data-stream-lineage=\"{}\" data-confidence=\"{:.4}\" />",
                        feat.id,
                        d.trim(),
                        off,
                        len,
                        lineage,
                        conf
                    )?;
                }
                Geometry::Polygon { rings } => {
                    let mut d = String::new();
                    for ring in rings {
                        for (i, c) in ring.iter().enumerate() {
                            if i == 0 {
                                d.push_str(&format!("M {} {} ", c[0], c[1]));
                            } else {
                                d.push_str(&format!("L {} {} ", c[0], c[1]));
                            }
                        }
                        d.push_str("Z ");
                    }
                    writeln!(
                        out,
                        "    <path id=\"{}\" fill-rule=\"evenodd\" d=\"{}\" data-offset=\"{}\" data-length=\"{}\" data-stream-lineage=\"{}\" data-confidence=\"{:.4}\" />",
                        feat.id,
                        d.trim(),
                        off,
                        len,
                        lineage,
                        conf
                    )?;
                }
                Geometry::MultiPolygon { polygons } => {
                    let mut d = String::new();
                    for poly in polygons {
                        for ring in poly {
                            for (i, c) in ring.iter().enumerate() {
                                if i == 0 {
                                    d.push_str(&format!("M {} {} ", c[0], c[1]));
                                } else {
                                    d.push_str(&format!("L {} {} ", c[0], c[1]));
                                }
                            }
                            d.push_str("Z ");
                        }
                    }
                    writeln!(
                        out,
                        "    <path id=\"{}\" fill-rule=\"evenodd\" d=\"{}\" data-offset=\"{}\" data-length=\"{}\" data-stream-lineage=\"{}\" data-confidence=\"{:.4}\" />",
                        feat.id,
                        d.trim(),
                        off,
                        len,
                        lineage,
                        conf
                    )?;
                }
                Geometry::CubicBezier { control_points } => {
                    if !control_points.is_empty() {
                        let mut d = format!(
                            "M {} {}",
                            control_points[0][0], control_points[0][1]
                        );
                        let mut idx = 1;
                        while idx + 2 < control_points.len() {
                            d.push_str(&format!(
                                " C {} {}, {} {}, {} {}",
                                control_points[idx][0],
                                control_points[idx][1],
                                control_points[idx + 1][0],
                                control_points[idx + 1][1],
                                control_points[idx + 2][0],
                                control_points[idx + 2][1]
                            ));
                            idx += 3;
                        }
                        writeln!(
                            out,
                            "    <path id=\"{}\" fill=\"none\" d=\"{}\" data-offset=\"{}\" data-length=\"{}\" data-stream-lineage=\"{}\" data-confidence=\"{:.4}\" />",
                            feat.id, d, off, len, lineage, conf
                        )?;
                    }
                }
                Geometry::RegularGrid {
                    origin,
                    spacing,
                    dims,
                    ..
                } => {
                    writeln!(
                        out,
                        "    <g id=\"{}\" data-grid-dims=\"{}x{}\" data-offset=\"{}\" data-length=\"{}\" data-stream-lineage=\"{}\" data-confidence=\"{:.4}\">",
                        feat.id, dims[0], dims[1], off, len, lineage, conf
                    )?;
                    for r in 0..dims[1] {
                        for c in 0..dims[0] {
                            let x = origin[0] + (c as f64) * spacing[0];
                            let y = origin[1] + (r as f64) * spacing[1];
                            writeln!(
                                out,
                                "      <circle cx=\"{}\" cy=\"{}\" r=\"{}\" />",
                                x,
                                y,
                                pt_r * 0.7
                            )?;
                        }
                    }
                    writeln!(out, "    </g>")?;
                }
                Geometry::SimpleMesh { vertices, faces } => {
                    let mut d = String::new();
                    for f in faces {
                        let i0 = f[0] as usize;
                        let i1 = f[1] as usize;
                        let i2 = f[2] as usize;
                        if i0 < vertices.len() && i1 < vertices.len() && i2 < vertices.len() {
                            d.push_str(&format!(
                                "M {} {} L {} {} L {} {} Z ",
                                vertices[i0][0],
                                vertices[i0][1],
                                vertices[i1][0],
                                vertices[i1][1],
                                vertices[i2][0],
                                vertices[i2][1]
                            ));
                        }
                    }
                    writeln!(
                        out,
                        "    <path id=\"{}\" d=\"{}\" data-offset=\"{}\" data-length=\"{}\" data-stream-lineage=\"{}\" data-confidence=\"{:.4}\" />",
                        feat.id,
                        d.trim(),
                        off,
                        len,
                        lineage,
                        conf
                    )?;
                }
            }
        }
        writeln!(out, "  </g>")?;
    }

    writeln!(out, "</svg>")?;
    out.flush()
}
